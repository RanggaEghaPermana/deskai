export function languageOf(config) {
    return config?.language in STRINGS ? config.language : 'en';
}

// t('pinTo', {mode: 'Writing'}) → "Pin to Writing" / "Sematkan ke Writing"
export function translator(language) {
    const strings = STRINGS[language] ?? STRINGS.en;
    return (key, params = {}) => {
        const entry = strings[key] ?? STRINGS.en[key];
        return typeof entry === 'function' ? entry(params) : entry ?? key;
    };
}
